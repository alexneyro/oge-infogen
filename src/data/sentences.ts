/**
 * Validates and filters sentences:
 * Discards phrases that:
 * - contain ellipsis (U+2026)
 * - contain non-breaking space (U+00A0)
 * - contain double space
 * - have leading or trailing space
 * - contain quotes: " « » “ ”
 * - after normalize('NFC') are shorter than 15 or longer than 90 characters
 * 
 * Returns remaining sentences normalized with NFC.
 */
export function getFilteredSentences(): string[] {
  const result: string[] = [];

  for (const raw of RAW_SENTENCES) {
    // 1. Check for leading or trailing space
    if (raw.startsWith(' ') || raw.endsWith(' ')) continue;

    // 2. Check for ellipsis (…)
    if (raw.includes('\u2026')) continue;

    // 3. Check for non-breaking space (\u00A0)
    if (raw.includes('\u00A0')) continue;

    // 4. Check for double space
    if (raw.includes('  ')) continue;

    // 5. Check for quotes: " « » “ ”
    if (/["«»“”]/.test(raw)) continue;

    // Normalize NFC
    const normalized = raw.normalize('NFC');

    // 6. Length check: between 15 and 90 characters inclusive
    if (normalized.length < 15 || normalized.length > 90) continue;

    result.push(normalized);
  }

  return result;
}
