import { describe, it, expect } from 'vitest';
import { pluralRu } from '../pluralize';

describe('pluralRu', () => {
  const forms: [string, string, string] = ['ученик', 'ученика', 'учеников'];

  it.each([
    [0, 'учеников'],
    [1, 'ученик'],
    [2, 'ученика'],
    [4, 'ученика'],
    [5, 'учеников'],
    [11, 'учеников'],
    [12, 'учеников'],
    [14, 'учеников'],
    [21, 'ученик'],
    [22, 'ученика'],
    [25, 'учеников'],
    [101, 'ученик'],
    [111, 'учеников'],
    [112, 'учеников'],
  ])('для %i возвращает «%s»', (n, expected) => {
    expect(pluralRu(n, ...forms)).toBe(expected);
  });

  it.each([
    [-1, 'ученик'],
    [-2, 'ученика'],
    [-4, 'ученика'],
    [-5, 'учеников'],
    [-11, 'учеников'],
    [-12, 'учеников'],
    [-14, 'учеников'],
    [-21, 'ученик'],
    [-22, 'ученика'],
    [-25, 'учеников'],
    [-101, 'ученик'],
    [-111, 'учеников'],
    [-112, 'учеников'],
  ])('для отрицательного %i обрабатывает модуль числа и возвращает «%s»', (n, expected) => {
    expect(pluralRu(n, ...forms)).toBe(expected);
  });
});
